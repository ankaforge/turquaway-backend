// Language Management //
function renderLangOptions() {
  $langList?.querySelectorAll("[data-language-option]")?.forEach(el => el.remove());
  
  Object.entries(LANGUAGE_NAMES).forEach(([code, label]) => {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "language-option";
    btn.dataset.languageOption = code;
    btn.textContent = label;
    btn.addEventListener("click", () => setLanguage(code) && closeLangMenu());
    $langList?.appendChild(btn);
  });
}

function toggleLangMenu() {
  const isOpen = $langBtn?.getAttribute("aria-expanded") === "true";
  isOpen ? closeLangMenu() : openLangMenu();
}

function openLangMenu() {
  if (!$langBtn || !$langList) return;
  $langList.classList.remove("hidden");
  $langBtn.setAttribute("aria-expanded", "true");
}

function closeLangMenu() {
  if (!$langBtn || !$langList) return;
  $langList.classList.add("hidden");
  $langBtn.setAttribute("aria-expanded", "false");
}

function updateLangUI(lang) {
  if ($langCurrent) $langCurrent.textContent = lang.toUpperCase();
  
  $langList?.querySelectorAll(".language-option").forEach(btn => {
    const isActive = btn.dataset.languageOption === lang;
    btn.classList.toggle("is-active", isActive);
    btn.setAttribute("aria-selected", String(isActive));
  });
}

function translatePage(lang) {
  const dict = translations[lang] || translations[DEFAULT_LANG];
  const pageTitleKey = document.querySelector("[data-page-title-i18n]")?.dataset.pageTitleI18n;
  
  document.title = pageTitleKey && dict[pageTitleKey] ? dict[pageTitleKey] : dict.pageTitle;
  document.documentElement.lang = lang;
  document.documentElement.dir = "ltr";
  document.body.dataset.locale = lang;
  
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (key in dict) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (key in dict) el.placeholder = dict[key];
  });
}

function setLanguage(lang) {
  const selected = translations[lang] ? lang : DEFAULT_LANG;
  translatePage(selected);
  localStorage.setItem(LANG_STORAGE_KEY, selected);
  updateLangUI(selected);
  document.dispatchEvent(new CustomEvent("turquaway:languagechange", { detail: { lang: selected } }));
  return true;
}

function getPreferredLang() {
  const stored = localStorage.getItem(LANG_STORAGE_KEY);
  if (stored && translations[stored]) return stored;
  
  const browserLangs = navigator.languages || [navigator.language];
  for (const lang of browserLangs) {
    const code = String(lang).split("-")[0].toLowerCase();
    if (translations[code]) return code;
  }
  return DEFAULT_LANG;
}


