// Carousels
function setupCarousel($carousel, options) {
  if (!$carousel) return;
  
  const { slides = "[data-city-slide]", dots = "[data-city-dot]", prev = "[data-city-prev]", next = "[data-city-next]", autoplay = 5500 } = options;
  
  const $slides = Array.from($carousel.querySelectorAll(slides));
  const $dots = Array.from($carousel.querySelectorAll(dots));
  const $prevBtn = $carousel.querySelector(prev);
  const $nextBtn = $carousel.querySelector(next);
  
  if (!$slides.length) return;
  
  let idx = 0;
  let autoplayId;
  
  const show = (n) => {
    idx = (n + $slides.length) % $slides.length;
    $slides.forEach((s, i) => {
      const isActive = i === idx;
      s.classList.toggle("opacity-100", isActive);
      s.classList.toggle("pointer-events-auto", isActive);
      s.classList.toggle("opacity-0", !isActive);
      s.classList.toggle("pointer-events-none", !isActive);
    });
    $dots.forEach((d, i) => {
      d.classList.toggle("scale-125", i === idx);
      d.classList.toggle("bg-white", i === idx);
      d.classList.toggle("bg-white/50", i !== idx);
    });
  };
  
  const start = () => {
    autoplayId = setInterval(() => show(idx + 1), autoplay);
  };
  
  const stop = () => clearInterval(autoplayId);
  
  const restart = () => { stop(); start(); };
  
  $prevBtn?.addEventListener("click", () => { show(idx - 1); restart(); });
  $nextBtn?.addEventListener("click", () => { show(idx + 1); restart(); });
  $dots.forEach((d, i) => d.addEventListener("click", () => { show(i); restart(); }));
  
  $carousel.addEventListener("mouseenter", stop);
  $carousel.addEventListener("mouseleave", start);
  
  show(0);
  start();
}



// Testimonial & Process Carousels
function setupSlideCarousel($carousel, options) {
  if (!$carousel) return;
  
  const { track = "[data-testimonial-track]", card = ".testimonial-card", dots = "[data-testimonial-dots]", autoplay = 4500 } = options;
  
  const $track = $carousel.querySelector(track);
  const $cards = Array.from($carousel.querySelectorAll(card));
  const $dotsContainer = document.querySelector(dots);
  
  if (!$track || !$cards.length) return;
  
  let cardsPerView = 1;
  let pageCount = 1;
  let activePage = 0;
  let autoplayId;
  
  const getCardsPerView = () => {
    if (innerWidth >= 1024) return 3;
    if (innerWidth >= 768) return 2;
    return 1;
  };
  
  const updateDots = () => {
    if (!$dotsContainer) return;
    $dotsContainer.querySelectorAll("button").forEach((d, i) => {
      const isActive = i === activePage;
      d.classList.toggle("scale-125", isActive);
      d.classList.toggle("bg-white", isActive);
      d.classList.toggle("bg-white/50", !isActive);
    });
  };
  
  const goToPage = (page, animate = true) => {
    activePage = (page + pageCount) % pageCount;
    const cardWidth = $cards[0].getBoundingClientRect().width;
    const firstIndex = Math.min(activePage * cardsPerView, Math.max(0, $cards.length - cardsPerView));
    $track.style.transitionDuration = animate ? "700ms" : "0ms";
    $track.style.transform = `translateX(-${firstIndex * cardWidth}px)`;
    updateDots();
  };
  
  const buildDots = () => {
    if (!$dotsContainer) return;
    $dotsContainer.innerHTML = "";
    for (let i = 0; i < pageCount; i++) {
      const btn = document.createElement("button");
      btn.type = "button";
      btn.className = "h-2.5 w-2.5 border-0 bg-white/50 transition-all";
      btn.addEventListener("click", () => { goToPage(i); restart(); });
      $dotsContainer.appendChild(btn);
    }
  };
  
  const recalc = () => {
    cardsPerView = getCardsPerView();
    pageCount = Math.max(1, Math.ceil($cards.length / cardsPerView));
    buildDots();
    goToPage(0, false);
  };
  
  const start = () => {
    autoplayId = setInterval(() => goToPage(activePage + 1), autoplay);
  };
  
  const restart = () => { clearInterval(autoplayId); start(); };
  
  $carousel.addEventListener("mouseenter", () => clearInterval(autoplayId));
  $carousel.addEventListener("mouseleave", start);
  $carousel.addEventListener("touchstart", () => clearInterval(autoplayId));
  $carousel.addEventListener("touchend", start);
  window.addEventListener("resize", recalc);
  document.addEventListener("visibilitychange", () => {
    document.hidden ? clearInterval(autoplayId) : start();
  });
  
  recalc();
  start();
}



function setupProcessCarousel() {
  if (!$processCarousel) return;

  const $track = $processCarousel.querySelector("[data-process-track]");
  const $cards = Array.from($processCarousel.querySelectorAll(".process-card"));
  const $viewport = $processCarousel.querySelector("[data-process-viewport]");
  const $prev = $processCarousel.querySelector("[data-process-prev]");
  const $next = $processCarousel.querySelector("[data-process-next]");
  const $dotsContainer = $processCarousel.querySelector("[data-process-dots]");

  if (!$track || !$cards.length) return;

  const total = $cards.length;
  let idx = 0;
  let autoplayId;

  const isMobile = () => innerWidth < 768;

  const syncHeight = () => {
    if (!isMobile() || !$viewport) return;
    const h = $cards[idx].getBoundingClientRect().height;
    $viewport.style.height = `${Math.ceil(h) + 24}px`;
  };

  const show = (n) => {
    idx = (n + total) % total;
    $cards.forEach((card, i) => {
      const delta = (i - idx + total) % total;
      const adjust = delta > total / 2 ? delta - total : delta;

      card.style.transition = "all 700ms ease";
      
      card.classList.toggle("is-active", adjust === 0);

      if (isMobile()) {
        card.style.transform = "translateX(-50%) scale(1)";
        card.style.opacity = adjust === 0 ? "1" : "0";
        card.style.zIndex = adjust === 0 ? "30" : "10";
        card.pointerEvents = adjust === 0 ? "auto" : "none";
        return;
      }

      card.classList.toggle("is-active", adjust === 0);

      if (adjust === 0) {
        card.style.transform = "translateX(-50%) scale(1)";
        card.style.opacity = "1";
        card.style.zIndex = "30";
      } else if (Math.abs(adjust) === 1) {
        const offset = adjust * 66;
        card.style.transform = `translateX(calc(-50% + ${offset}%)) scale(0.9)`;
        card.style.opacity = "0.55";
        card.style.zIndex = "20";
      } else {
        const far = adjust > 0 ? 150 : -150;
        card.style.transform = `translateX(calc(-50% + ${far}%)) scale(0.82)`;
        card.style.opacity = "0";
        card.style.zIndex = "10";
      }
    });

    $dotsContainer?.querySelectorAll("button").forEach((d, i) => {
      const isActive = i === idx;
      d.classList.toggle("scale-125", isActive);
      d.classList.toggle("bg-white", isActive);
      d.classList.toggle("bg-white/50", !isActive);
    });

    syncHeight();
  };

  const buildDots = () => {
    if (!$dotsContainer) return;
    $dotsContainer.innerHTML = "";
    for (let i = 0; i < total; i++) {
      const btn = document.createElement("button");
      btn.type = "button";
      btn.className = "h-2.5 w-2.5 border-0 bg-white/50 transition-all";
      btn.addEventListener("click", () => { show(i); restart(); });
      $dotsContainer.appendChild(btn);
    }
  };

  const start = () => {
    autoplayId = setInterval(() => show(idx + 1), CAROUSEL_AUTOPLAY.process);
  };

  const restart = () => { clearInterval(autoplayId); start(); };

  $prev?.addEventListener("click", () => { show(idx - 1); restart(); });
  $next?.addEventListener("click", () => { show(idx + 1); restart(); });

  $processCarousel.addEventListener("mouseenter", () => clearInterval(autoplayId));
  $processCarousel.addEventListener("mouseleave", start);
  $processCarousel.addEventListener("touchstart", () => clearInterval(autoplayId));
  $processCarousel.addEventListener("touchend", start);

  window.addEventListener("resize", () => { syncHeight(); });
  document.addEventListener("visibilitychange", () => {
    document.hidden ? clearInterval(autoplayId) : start();
  });

  buildDots();
  show(0);
  start();
}


